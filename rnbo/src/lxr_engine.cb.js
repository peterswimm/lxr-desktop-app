// LXR drum engine for RNBO codebox~
//
// A port of the LXR V2 firmware sound engine (Core/Src/Soundengine): three drum voices,
// snare/clap, cymbal, open/closed hihat, per-voice LFO and velocity modulation, sample
// rate reduction, the mixer and the FX bus (drive, ring modBuf, compressor, delay).
//
// The firmware renders blocks of 64 samples: envelopes, LFOs, modulation and triggers
// run once per block, the audio paths run per sample in 16-bit integer steps. This port
// keeps that structure on purpose (same block size, same order of operations, same
// 16-bit wrap/saturation points, same integer phase accumulators) so it sounds like the
// hardware and can be checked sample by sample against the original C code
// (see rnbo/test). Triggers and parameter changes take effect at the next 64-sample
// block, like on the hardware.
//
// Parameters keep the LXR's own value ranges, so an LXR kit's values can be entered
// 1:1. In the Move patch each one is an RNBO [param] that sets the @param here through
// [set <name>]. The @param block, scanParams() and the tables are generated by
// rnbo/tools/build.py from the firmware sources; edit this file, not the generated one.
//
// The sequencer (src/lxr_seq.cb.js) runs in the message domain and plays the voices
// through in2..in8. The parameter locks of its steps arrive in the auto_* attributes and
// work like the firmware's automation nodes (automationNode.c): each trigger first
// puts the track's previous lock targets back to their parameter values, then sets the
// new ones.
//
// Inlets  in1:      [set <param>] messages for the parameters (no signal).
//         in2..in8: triggers for Drum1, Drum2, Drum3, Snare, Cymbal, closed and open hihat.
//                   Each value is  count * 16384 + note * 128 + velocity ; a new value
//                   triggers the voice (count only has to change between triggers).
// Outlets out1/out2: LXR output 1 (stereo), out3/out4: LXR output 2 (stereo).

